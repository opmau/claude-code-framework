#!/bin/bash
# ============================================================================
# check-public-text.sh — PreToolUse hook for Bash (publishing commands)
# ============================================================================
# Scans text about to become public — commit messages, PR bodies, release
# notes, issue comments, and staged public docs — for two things an agent
# reliably gets wrong:
#
#   1. Private data. Real measured figures, identifiers, local paths. Once
#      pushed, a commit message cannot be scrubbed by a forward fix.
#   2. Session narrative. Text drafted from the working session rather than
#      from the change, addressed to whoever watched it happen.
#
# Does NOT block — provides context so Claude can self-correct before the
# command runs. See .claude/rules/public-writing.md for the standard.
#
# DO NOT EDIT THIS FILE TO CUSTOMIZE IT. bin/update.sh copies it over on every
# framework update, which would silently revert your changes. Set the
# PUBLIC_TEXT_* variables in .claude/project.conf instead — that file is never
# touched by the updater.
# ============================================================================

INPUT=$(cat)
COMMAND=$(echo "$INPUT" | jq -r '.tool_input.command // empty')

[ -z "$COMMAND" ] && exit 0

# Only trigger on commands that publish text to somewhere a stranger can read.
if ! echo "$COMMAND" | grep -Eq 'git commit|gh pr (create|edit)|gh release (create|edit)|gh issue (create|comment|edit)'; then
  exit 0
fi

# --- Project-local configuration --------------------------------------------
HOOK_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
PROJECT_CONF="$HOOK_DIR/../project.conf"
# shellcheck source=/dev/null
[ -f "$PROJECT_CONF" ] && . "$PROJECT_CONF"

# Phrases that mark text as a narrative of the working session.
DEFAULT_TELLS='found while|caught by|turned out|it emerged|masked because|mostly masked|for the first time|never worked|had always been|while implementing|during implementation|as it happens|we discovered|I discovered|I found|my earlier|in this session|all green|tests pass'
TELLS="${PUBLIC_TEXT_TELLS:-$DEFAULT_TELLS}"
[ -n "${PUBLIC_TEXT_TELLS_EXTRA:-}" ] && TELLS="$TELLS|$PUBLIC_TEXT_TELLS_EXTRA"

# Paths and identifiers that should never reach a public artifact.
DEFAULT_PRIVATE='[A-Za-z]:\\\\Users\\\\|/home/[a-z]|/Users/[a-z]|OneDrive|\.env\b|id_rsa|0x[a-fA-F0-9]{40}'
PRIVATE="${PUBLIC_TEXT_PRIVATE:-$DEFAULT_PRIVATE}"
[ -n "${PUBLIC_TEXT_PRIVATE_EXTRA:-}" ] && PRIVATE="$PRIVATE|$PUBLIC_TEXT_PRIVATE_EXTRA"

# Set to 1 in project.conf for projects whose public docs legitimately quote
# precise measured numbers (benchmarks, published datasets).
ALLOW_FIGURES="${PUBLIC_TEXT_ALLOW_FIGURES:-0}"

# --- Collect the text about to be published ---------------------------------
# Inline bodies and messages, plus any heredoc the command carries.
#
# Strip the parts of the command line that are NOT published content, or the
# scan reports the caller's own working directory on every commit:
#   - `cd <path>` prefixes
#   - the PATH argument to --body-file/-F (its CONTENTS are read separately)
#   - -C/--git-dir path arguments
# A hook that warns on every invocation stops being read, so precision here
# matters more than catching a leak that happens to sit inside a `cd`.
TEXT=$(printf '%s' "$COMMAND" \
  | sed -E 's/(^|[;&|]) *cd +("[^"]*"|'"'"'[^'"'"']*'"'"'|[^ ;&|]+)/\1/g' \
  | sed -E 's/(--body-file|-F|-C|--git-dir)[ =]+("[^"]*"|'"'"'[^'"'"']*'"'"'|[^ ]+)/\1/g')

# --body-file / -F <path> — the common path for long bodies.
BODY_FILE=$(echo "$COMMAND" | grep -oE '(--body-file|-F)[ =]+[^ ]+' | head -1 | sed -E 's/^(--body-file|-F)[ =]+//' | tr -d '"'"'"'')
if [ -n "$BODY_FILE" ] && [ "$BODY_FILE" != "-" ] && [ -f "$BODY_FILE" ]; then
  TEXT="$TEXT
$(cat "$BODY_FILE" 2>/dev/null)"
fi

# Staged changes to files a stranger reads, on commit.
#
# Framework internals under .claude/ are excluded: a file that documents this
# standard necessarily quotes the phrasings it warns about, and would flag
# itself. Any other file can opt out by containing the marker
# "public-text-check: ignore" — use it for style guides and linter fixtures,
# not to silence a genuine finding.
if echo "$COMMAND" | grep -q 'git commit'; then
  STAGED_DOCS=$(git diff --cached --name-only 2>/dev/null \
    | grep -Ei '(^|/)(CHANGELOG|README|CONTRIBUTING|SECURITY)|^docs/|\.md$' \
    | grep -Ev '(^|/)\.claude/' \
    | head -20)
  for f in $STAGED_DOCS; do
    [ -f "$f" ] || continue
    grep -q 'public-text-check: ignore' "$f" 2>/dev/null && continue
    TEXT="$TEXT
$(git diff --cached -U0 -- "$f" 2>/dev/null | grep '^+' | sed 's/^+//')"
  done
fi

[ -z "$TEXT" ] && exit 0

# --- Scan --------------------------------------------------------------------
FINDINGS=""

PRIVATE_HITS=$(echo "$TEXT" | grep -inE "$PRIVATE" | head -4 | cut -c1-160)
if [ -n "$PRIVATE_HITS" ]; then
  FINDINGS="PRIVATE DATA / PATHS:
$PRIVATE_HITS"
fi

if [ "$ALLOW_FIGURES" != "1" ]; then
  # Numbers that look measured rather than structural: comma-grouped thousands,
  # or 2+ decimal places. Version strings (x.y.z) and dates are excluded.
  FIGURE_HITS=$(echo "$TEXT" \
    | grep -vE '^\+*\s*(version|Version|v[0-9])' \
    | grep -oE '[0-9]{1,3}(,[0-9]{3})+(\.[0-9]+)?|[0-9]+\.[0-9]{2,}' \
    | grep -vE '^[0-9]+\.[0-9]+\.[0-9]+$' \
    | sort -u | head -6 | tr '\n' ' ')
  if [ -n "$FIGURE_HITS" ]; then
    FINDINGS="$FINDINGS
MEASURED-LOOKING FIGURES: $FIGURE_HITS
  If any of these is a real value read from a live system or account, remove it.
  State the shape of the effect instead. Illustrative values are fine."
  fi
fi

TELL_HITS=$(echo "$TEXT" | grep -inE "$TELLS" | head -4 | cut -c1-160)
if [ -n "$TELL_HITS" ]; then
  FINDINGS="$FINDINGS
SESSION NARRATIVE:
$TELL_HITS"
fi

[ -z "$FINDINGS" ] && exit 0

# jq -Rs produces a correctly escaped JSON string for arbitrary text.
MESSAGE=$(printf 'PUBLIC TEXT WARNING — this command publishes text a stranger can read.\n\n%s\n\nBefore running it:\n  1. Remove any real measured value or identifier. A pushed commit message cannot be scrubbed by a forward fix.\n  2. Cut sentences that describe how the work went rather than what changed.\n  3. After publishing, FETCH the artifact back from its published source and read it. Do not assert it is clean.\n\nStandard: .claude/rules/public-writing.md   Cold review: docs-reviewer agent.' "$FINDINGS" | jq -Rs .)

cat << EOF
{
  "hookSpecificOutput": {
    "hookEventName": "PreToolUse",
    "additionalContext": $MESSAGE
  }
}
EOF

# Always allow — advisory, not blocking.
exit 0
